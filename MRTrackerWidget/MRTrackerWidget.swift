import WidgetKit
import SwiftUI

// `MergeRequestEntry` is declared in Shared/WidgetTimelineBuilder.swift as a plain
// (non-WidgetKit) struct so it's testable from MyAppTests. `TimelineEntry` only requires
// `var date: Date { get }`, which it already has, so this conformance is free.
extension MergeRequestEntry: TimelineEntry {}

struct Provider: TimelineProvider {
    func placeholder(in context: Context) -> MergeRequestEntry {
        WidgetPreviewSamples.manyMixedOk
    }

    func getSnapshot(in context: Context, completion: @escaping (MergeRequestEntry) -> Void) {
        if context.isPreview {
            completion(WidgetPreviewSamples.manyMixedOk)
            return
        }
        completion(Self.readEntries().first ?? WidgetPreviewSamples.manyMixedOk)
    }

    func getTimeline(in context: Context, completion: @escaping (Timeline<MergeRequestEntry>) -> Void) {
        // See WidgetTimelineBuilder's doc comment: reloads are pushed by the host app via
        // WidgetCenter (debounced, MRT-041) whenever the snapshot changes, so there is
        // nothing to poll for here. `.never` + the builder's own staleness entry (when
        // applicable) is the full policy.
        let entries = Self.readEntries()
        completion(Timeline(entries: entries, policy: .never))
    }

    /// Reads the shared snapshot (if the App Group container is reachable at all) and turns
    /// it into timeline entries via the pure builder. Never throws, never calls the network.
    private static func readEntries(now: Date = Date()) -> [MergeRequestEntry] {
        let result: SnapshotReadResult?
        do {
            let store = try SnapshotFileStore.appGroup(containerURL: AppGroup.containerURL, identifier: AppGroup.identifier)
            result = store.read()
        } catch {
            // SnapshotFileStore.StoreError.appGroupContainerUnavailable — no file to read.
            result = nil
        }
        return WidgetTimelineBuilder.makeEntries(for: result, now: now)
    }
}

struct MRTrackerWidgetEntryView: View {
    var entry: Provider.Entry

    @Environment(\.widgetFamily) private var family

    var body: some View {
        switch family {
        case .systemSmall:
            SmallWidgetView(entry: entry)
        case .systemLarge:
            LargeWidgetView(entry: entry)
        default:
            MediumWidgetView(entry: entry)
        }
    }
}

struct MRTrackerWidget: Widget {
    // Kept EXACTLY as generated by the Xcode template. Sourced from
    // Shared/WidgetKinds.swift so this value and WidgetCenter.reloadTimelines(ofKind:)
    // callers in the host app (MRT-041) can never drift apart.
    let kind: String = WidgetKinds.mergeRequests

    var body: some WidgetConfiguration {
        StaticConfiguration(kind: kind, provider: Provider()) { entry in
            MRTrackerWidgetEntryView(entry: entry)
        }
        .configurationDisplayName("GitLab MRs")
        .description("Shows your open GitLab merge requests and their pipeline, approval, and merge status.")
        .supportedFamilies([.systemSmall, .systemMedium, .systemLarge])
    }
}

